package com.sasha.radio.download;

import com.google.gson.GsonBuilder;
import com.google.gson.JsonArray;
import com.google.gson.JsonElement;
import com.google.gson.JsonObject;
import com.google.gson.JsonParser;

import java.io.IOException;
import java.net.URI;
import java.net.URLEncoder;
import java.net.http.HttpClient;
import java.net.http.HttpRequest;
import java.net.http.HttpResponse;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.StandardCopyOption;
import java.security.MessageDigest;
import java.security.NoSuchAlgorithmException;
import java.time.Duration;
import java.util.ArrayList;
import java.util.HexFormat;
import java.util.List;
import java.util.Locale;
import java.util.Map;
import java.util.TreeMap;
import java.util.logging.Logger;
import java.util.stream.Stream;

/**
 * Brings the song folder in line with a song repository. The repository has an index.json listing every
 * song's path, size and SHA-1 (generated by the songIndex Gradle task).
 *
 * <ul>
 *   <li>Songs missing locally, or changed in the repository, are downloaded.</li>
 *   <li>Songs removed from (or renamed in) the repository are deleted locally, but only files this
 *       downloader put there and that are still unchanged. Their record is kept in {@value #RECORD_FILE}.</li>
 *   <li>Songs an admin added by hand are never touched.</li>
 * </ul>
 */
public final class SongDownloader {

    private static final Duration TIMEOUT = Duration.ofSeconds(20);
    private static final long MAX_SONG_BYTES = 8L * 1024 * 1024;
    /** In the song folder: path → SHA-1 of every file that came from the repository. */
    static final String RECORD_FILE = ".repository-files.json";

    private final HttpClient http = HttpClient.newBuilder()
            .connectTimeout(TIMEOUT)
            .followRedirects(HttpClient.Redirect.NORMAL)
            .build();
    private final Logger logger;
    private final String userAgent;

    public SongDownloader(Logger logger, String version) {
        this.logger = logger;
        this.userAgent = "Radio-Plugin/" + version;
    }

    public record Result(int added, int updated, int removed, int failed, int total) {
        public boolean changed() {
            return added + updated + removed > 0;
        }
    }

    /** Blocking: call off the main thread. */
    public Result sync(String repository, Path songFolder) throws IOException, InterruptedException {
        JsonObject index = JsonParser.parseString(get(repository + "index.json", String.class)).getAsJsonObject();
        JsonArray songs = index.getAsJsonArray("songs");
        if (songs == null) throw new IOException("index.json has no \"songs\" list");

        Files.createDirectories(songFolder);
        Path root = songFolder.toAbsolutePath().normalize();
        Map<String, String> previous = readRecord(root);
        Map<String, String> current = new TreeMap<>();
        int added = 0, updated = 0, failed = 0;
        for (JsonElement element : songs) {
            String path = "?";
            try {
                JsonObject entry = element.getAsJsonObject();
                path = entry.get("path").getAsString();
                String sha1 = entry.get("sha1").getAsString().toLowerCase(Locale.ROOT);

                Path target = safeResolve(root, path);
                boolean exists = Files.isRegularFile(target);
                if (exists) {
                    String local = sha1(Files.readAllBytes(target));
                    if (sha1.equals(local)) {
                        current.put(path, sha1);
                        continue;
                    }
                    // Same name but different contents, and not something we downloaded: an admin's own file.
                    if (!local.equals(previous.get(path))) {
                        logger.info("Keeping your own " + path + " (it differs from the repository's copy).");
                        continue;
                    }
                }

                byte[] data = get(repository + encodePath(path), byte[].class);
                if (data.length > MAX_SONG_BYTES) throw new IOException("file is too large");
                if (!sha1.equals(sha1(data))) throw new IOException("checksum does not match index.json");

                Files.createDirectories(target.getParent());
                Path temp = Files.createTempFile(target.getParent(), ".download-", ".tmp");
                try {
                    Files.write(temp, data);
                    Files.move(temp, target, StandardCopyOption.REPLACE_EXISTING, StandardCopyOption.ATOMIC_MOVE);
                } finally {
                    Files.deleteIfExists(temp);
                }
                current.put(path, sha1);
                if (exists) updated++;
                else added++;
            } catch (IOException | RuntimeException e) {
                failed++;
                logger.warning("Could not download " + path + ": " + e.getMessage());
            }
        }

        int removed = 0;
        for (Map.Entry<String, String> old : previous.entrySet()) {
            if (current.containsKey(old.getKey())) continue;
            try {
                Path target = safeResolve(root, old.getKey());
                // Only delete what we downloaded and nobody has edited since.
                if (Files.isRegularFile(target) && old.getValue().equals(sha1(Files.readAllBytes(target)))) {
                    Files.delete(target);
                    removed++;
                    deleteEmptyParents(target.getParent(), root);
                }
            } catch (IOException e) {
                logger.warning("Could not remove " + old.getKey() + ": " + e.getMessage());
            }
        }

        writeRecord(root, current);
        return new Result(added, updated, removed, failed, songs.size());
    }

    private static void deleteEmptyParents(Path folder, Path root) throws IOException {
        while (folder != null && !folder.equals(root) && folder.startsWith(root)) {
            try (Stream<Path> children = Files.list(folder)) {
                if (children.findAny().isPresent()) return;
            }
            Files.delete(folder);
            folder = folder.getParent();
        }
    }

    private Map<String, String> readRecord(Path root) {
        Path file = root.resolve(RECORD_FILE);
        Map<String, String> record = new TreeMap<>();
        if (!Files.isRegularFile(file)) return record;
        try {
            JsonObject json = JsonParser.parseString(Files.readString(file, StandardCharsets.UTF_8)).getAsJsonObject();
            json.entrySet().forEach(e -> record.put(e.getKey(), e.getValue().getAsString()));
        } catch (IOException | RuntimeException e) {
            logger.warning("Ignoring unreadable " + RECORD_FILE + ": " + e.getMessage());
        }
        return record;
    }

    private static void writeRecord(Path root, Map<String, String> record) throws IOException {
        JsonObject json = new JsonObject();
        record.forEach(json::addProperty);
        Files.writeString(root.resolve(RECORD_FILE), new GsonBuilder().setPrettyPrinting().create().toJson(json),
                StandardCharsets.UTF_8);
    }

    @SuppressWarnings("unchecked")
    private <T> T get(String url, Class<T> type) throws IOException, InterruptedException {
        HttpRequest request = HttpRequest.newBuilder(URI.create(url))
                .timeout(TIMEOUT)
                .header("User-Agent", userAgent)
                .GET()
                .build();
        HttpResponse<?> response = type == String.class
                ? http.send(request, HttpResponse.BodyHandlers.ofString(StandardCharsets.UTF_8))
                : http.send(request, HttpResponse.BodyHandlers.ofByteArray());
        if (response.statusCode() != 200) throw new IOException("HTTP " + response.statusCode() + " for " + url);
        return (T) response.body();
    }

    /** Resolves a path from index.json inside the song folder, refusing anything that would escape it. */
    private static Path safeResolve(Path root, String relative) throws IOException {
        if (!relative.toLowerCase(Locale.ROOT).endsWith(".nbs")) throw new IOException("not an .nbs file");
        Path target = root.resolve(relative).normalize();
        if (!target.startsWith(root) || target.equals(root)) throw new IOException("path is outside the song folder");
        return target;
    }

    /** "TV & Film/My Song.nbs" → "TV%20%26%20Film/My%20Song.nbs" */
    private static String encodePath(String path) {
        List<String> parts = new ArrayList<>();
        for (String part : path.split("/")) {
            parts.add(URLEncoder.encode(part, StandardCharsets.UTF_8).replace("+", "%20"));
        }
        return String.join("/", parts);
    }

    private static String sha1(byte[] data) {
        try {
            return HexFormat.of().formatHex(MessageDigest.getInstance("SHA-1").digest(data));
        } catch (NoSuchAlgorithmException e) {
            throw new IllegalStateException(e);
        }
    }
}
